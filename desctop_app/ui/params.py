POSITION_MAX = 4095                # шаг, 0.087890625 градуса
SPEED_MAX = 3400                   # шаг/с
STEPS_PER_TURN = POSITION_MAX + 1  # 4096 шагов на полный оборот

# Параметры, которые можно задавать и в градусах. У таких строк на вкладке
# два связанных поля: шаги и градусы.
POSITION_KEYS = frozenset({"min_pos", "max_pos", "home_zero", "home_travel"})


def steps_to_degrees(steps: int) -> float:
    return steps * 360.0 / STEPS_PER_TURN


def degrees_to_steps(degrees: float) -> int:
    """Округляет до ближайшего целого шага: промежуточных положений у
    энкодера нет, один шаг это 0.087890625 градуса."""
    return round(degrees * STEPS_PER_TURN / 360.0)

